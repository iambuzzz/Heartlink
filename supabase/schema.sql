-- HeartLink database (Postgres / Supabase).
-- Gift content lives as JSON validated by the template definition in src/lib/templates.

create extension if not exists pgcrypto;

-- Anonymous on first visit; phone or email is attached at checkout.
create table users (
  id uuid primary key default gen_random_uuid(),
  device_id text unique,
  phone text unique,
  email text unique,
  credits int not null default 0 check (credits >= 0),
  created_at timestamptz not null default now()
);

create table templates (
  slug text primary key,
  name text not null,
  price_inr int not null check (price_inr >= 0),
  is_active boolean not null default true,
  sort_order int not null default 0
);

-- 'paused' = payment couldn't be confirmed; 'removed' = taken down.
create type gift_status as enum ('draft', 'paid', 'paused', 'removed');

create table gifts (
  id uuid primary key default gen_random_uuid(),
  -- Public, unguessable link id: /g/<slug> (12 url-safe chars, generated by the app)
  slug text not null unique,
  owner_id uuid not null references users(id) on delete cascade,
  template_slug text not null references templates(slug),
  content jsonb not null,
  status gift_status not null default 'draft',
  is_group boolean not null default false,
  reveal_at timestamptz,
  password_hash text,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index gifts_owner_idx on gifts (owner_id, created_at desc);

-- Photos and voice notes, stored in object storage; only the key is kept here.
create table media (
  id uuid primary key default gen_random_uuid(),
  gift_id uuid not null references gifts(id) on delete cascade,
  kind text not null check (kind in ('photo', 'voice')),
  storage_key text not null,
  caption text,
  position int not null default 0,
  created_at timestamptz not null default now()
);

-- Group gifts: each contributor adds a message, photo or voice note through an invite link.
create table contributions (
  id uuid primary key default gen_random_uuid(),
  gift_id uuid not null references gifts(id) on delete cascade,
  author_name text not null,
  message text,
  media_id uuid references media(id) on delete set null,
  is_hidden boolean not null default false,
  created_at timestamptz not null default now()
);

-- The recipient's reaction, sent back to the sender (and contributors).
create table replies (
  id uuid primary key default gen_random_uuid(),
  gift_id uuid not null references gifts(id) on delete cascade,
  message text,
  media_id uuid references media(id) on delete set null,
  created_at timestamptz not null default now()
);

-- Direct UPI: the buyer pays a unique amount (e.g. ₹99.37) to our business UPI ID and
-- submits the 12-digit UTR. 'claimed' unlocks the gift at once; an admin later marks it
-- 'verified' against the bank statement, or 'rejected' (which pauses the gift).
create type order_status as enum ('created', 'claimed', 'verified', 'rejected');

create table orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references users(id),
  gift_id uuid references gifts(id),
  -- 'gift' unlocks one gift; 'pack' adds credits.
  kind text not null check (kind in ('gift', 'pack')),
  credits int not null default 0,
  amount_paise int not null check (amount_paise > 0),
  status order_status not null default 'created',
  utr text unique check (utr ~ '^[0-9]{12}$'),
  claimed_at timestamptz,
  verified_at timestamptz,
  created_at timestamptz not null default now()
);
create index orders_open_amount_idx on orders (amount_paise, created_at) where status in ('created', 'claimed');

create table events (
  id bigint generated always as identity primary key,
  gift_id uuid not null references gifts(id) on delete cascade,
  kind text not null check (kind in ('open', 'complete', 'reply', 'share', 'hug')),
  created_at timestamptz not null default now()
);
create index events_gift_idx on events (gift_id, created_at desc);

-- Only the server (service-role key) touches data. RLS on with no policies means the
-- public anon key can read or write nothing.
alter table users enable row level security;
alter table templates enable row level security;
alter table gifts enable row level security;
alter table media enable row level security;
alter table contributions enable row level security;
alter table replies enable row level security;
alter table orders enable row level security;
alter table events enable row level security;

-- Grant the server role explicitly, so this works even when the project doesn't
-- auto-expose new tables to the Data API.
grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;

